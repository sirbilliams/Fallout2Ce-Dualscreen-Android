int main()
{
    using namespace fallout;

    CHECK(mp3DecoderIsFilePath("data/sound/sfx/ambient/wind.mp3"));
    CHECK(mp3DecoderIsFilePath("WIND.MP3"));
    CHECK(!mp3DecoderIsFilePath("wind.ogg"));
    CHECK(!mp3DecoderIsFilePath("mp3"));

    AudioFileInfo info = {};
    unsigned char* data = nullptr;
    int size = 0;
    CHECK(mp3DecoderDecodeMemory(kTinyMp3, sizeof(kTinyMp3), &info, &data, &size));
    CHECK(data != nullptr && size > 0 && size % 2 == 0);
    CHECK(info.channels == 1 && info.sampleRate == 22050 && info.bitsPerSample == 16);
    // 0.2 s at 22050 Hz is ~4410 frames; allow codec padding.
    CHECK(size / 2 >= 4000 && size / 2 <= 6000);
    bool nonSilent = false;
    for (int i = 0; i < size; i++) {
        if (data[i] != 0) {
            nonSilent = true;
            break;
        }
    }
    CHECK(nonSilent);
    internal_free_safe(data, __FILE__, __LINE__);

    // Garbage must fail cleanly (this is what a bad .mp3/.acm looks like).
    unsigned char garbage[512];
    for (size_t i = 0; i < sizeof(garbage); i++) {
        garbage[i] = static_cast<unsigned char>(i * 37 + 11);
    }
    data = nullptr;
    CHECK(!mp3DecoderDecodeMemory(garbage, sizeof(garbage), &info, &data, &size));
    CHECK(data == nullptr);
    CHECK(!mp3DecoderDecodeMemory(nullptr, 0, &info, &data, &size));
    CHECK(!mp3DecoderDecodeMemory(kTinyMp3, 3, &info, &data, &size));

    std::cout << "mp3_decoder_test ok\n";
    return 0;
}
